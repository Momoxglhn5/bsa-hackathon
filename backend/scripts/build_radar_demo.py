"""Build a focused offline jury demo from a recorded REAL Data delivery.

All financial results come from Core engines; the browser only selects cached
cases. Conditional closing-plan assumptions never modify the observed dataset.
"""
import argparse
import hashlib
import json
import sys
from decimal import Decimal
from pathlib import Path

sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from app.analytics.dataset import AnalyticsSnapshot,load_snapshot
from app.analytics.service import AnalyticsService
from app.analytics.valuation import value_position
from app.decision.schemas import DecisionRequest
from app.graph.builder import build_graph
from app.models.evidence import EvidenceDTO
from app.stress.schemas import SimulationRequest

ROOT=Path(__file__).resolve().parents[2]


def build(snapshot,quotes):
    position=next(p for p in snapshot.positions if p.position_id=='pos_simulated_2000000usd')
    strategy=snapshot.strategy(position.strategy_id)
    if snapshot.market(position).data_mode.value!='REAL' or position.kind.value!='SIMULATED':
        raise ValueError('demo requires a real market and explicitly simulated 2M USD fund')
    snapshot=snapshot.model_copy(update={'positions':(position,),
        'quotes':tuple(q for q in snapshot.quotes if q.position_id==position.position_id)})
    valuation=value_position(snapshot,position,now=snapshot.as_of)
    if valuation.equity_usd is None or len(snapshot.quotes)!=1:
        raise ValueError('fresh replay valuation and one sized quote required')
    graph=build_graph(snapshot,strategy.strategy_id)
    assumption={'closing_feasible':True,'repayment_liquidity_confirmed':True,
        'gas_cost_usd':'300','extra_fees_usd':'0','basis':'USER_ASSUMPTION'}
    text=json.dumps(assumption,sort_keys=True)
    identity='ev_'+hashlib.sha256(text.encode()).hexdigest()[:24]
    proof=EvidenceDTO(evidence_id=identity,chain_id=1,data_mode='REAL',source_kind='USER_INPUT',
        source_id='demo_closing_assumption',method='illustrative_closing_plan',
        fetched_at=snapshot.as_of,payload_sha256=hashlib.sha256(text.encode()).hexdigest(),status='OK',
        decoded_excerpt={k:str(v) for k,v in assumption.items()})
    quote=snapshot.quotes[0]
    conditional_quote=type(quote).model_validate({**quote.model_dump(),**assumption,
        'evidence_ids':quote.evidence_ids+(identity,)})
    conditional=snapshot.model_copy(update={'quotes':(conditional_quote,),
                                            'evidence':snapshot.evidence+(proof,)})
    services={'observed':AnalyticsService(snapshot),'conditional':AnalyticsService(conditional)}
    cases={}
    for shock in (10,20,40):
        cases[str(shock)]={}
        for mode,service in services.items():
            stress=service.simulate(SimulationRequest(strategy_id=strategy.strategy_id,
                position_id=position.position_id,horizon_days=7,scenario_type='UNAUTHORIZED_MINTING',
                scenario_scope='HYPOTHETICAL',target_node_id=position.collateral_asset.asset_id,
                parameters={'assumed_token_haircut_ratio':str(Decimal(shock)/100)}))
            decisions={}
            for probability in (2,10,20):
                decisions[str(probability)]=service.decide(DecisionRequest(strategy_id=strategy.strategy_id,
                    position_id=position.position_id,horizon_days=7,
                    scenario_assumptions=[{'loss_scenario_ref':stress.simulation_id,
                        'probability_over_horizon':str(Decimal(probability)/100)}],
                    exit_quote_id=quote.quote_id,estimated_net_carry_usd=Decimal('1000'),
                    carry_explanation='USER ASSUMPTION: net carry of 1000 USD over seven days; not an ML forecast')).model_dump(mode='json')
            cases[str(shock)][mode]={'stress':stress.model_dump(mode='json'),'decisions':decisions}
    # Both pedagogical verdicts must be generated by Core, never hardcoded.
    if (cases['20']['conditional']['decisions']['2']['verdict']!='STAY'
            or cases['20']['conditional']['decisions']['10']['verdict']!='EXIT'):
        raise ValueError('recorded delivery does not produce the documented pedagogical reversal')
    if cases['20']['observed']['decisions']['2']['verdict'] is not None:
        raise ValueError('observed case must not claim a verified closing plan')
    return {'version':'radar-jury-demo-v1','as_of':snapshot.as_of.isoformat(),
        'snapshot_sha256':hashlib.sha256(snapshot.model_dump_json().encode()).hexdigest(),
        'position':position.model_dump(mode='json'),'valuation':valuation.model_dump(mode='json'),
        'graph':graph.model_dump(mode='json'),'quotes':quotes,'cases':cases,
        'evidence':[e.model_dump(mode='json') for e in conditional.evidence],
        'closing_assumptions':assumption,'net_carry_assumption_usd':'1000',
        'mc':json.loads((ROOT/'docs/validation/monte_carlo_20261011/report.json').read_text())}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--delivery',type=Path,default=ROOT/'docs/demo/radar/source')
    parser.add_argument('--output',type=Path,default=ROOT/'docs/demo/radar')
    args=parser.parse_args()
    data=build(load_snapshot(args.delivery/'analytics_snapshot.json'),
               json.loads((args.delivery/'exit_quotes.json').read_text())['records'])
    args.output.mkdir(parents=True,exist_ok=True)
    (args.output/'demo-data.json').write_text(json.dumps(data,indent=2)+'\n')
    template=(ROOT/'backend/app/fixtures/radar_demo_template.html').read_text()
    embedded=json.dumps(data,separators=(',',':')).replace('<','\\u003c')
    (args.output/'index.html').write_text(template.replace('__DEMO_DATA__',embedded))
    print('Built recorded REAL market demo, simulated fund, conditional closing assumptions')


if __name__=='__main__':
    main()
